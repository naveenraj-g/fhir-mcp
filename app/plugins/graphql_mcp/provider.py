"""
The `graphql_mcp` engine of the graphql plugin: tools generated by the
third-party graphql-mcp library (https://graphql-mcp.com) instead of our own
code in app.plugins.graphql. Selected per connector with
`graphql.engine: graphql_mcp`; everything else in the graphql block (endpoint,
schema_file, include/exclude, include_mutations) means the same as for the
native engine.

Division of labour:

  graphql-mcp   schema → tools: argument schemas, the selection set, the
                operation document, annotations, and its own recovery from
                fields the token isn't allowed to read.
  this module   which root fields become tools (include/exclude), and the
                HTTP call itself — through the connector's httpx2 client, so
                token passthrough, Medplum client credentials and the
                refetch-on-401 work exactly as for the native engine.

Three library behaviours are deliberately worked around:

- Its own HTTP layer (aiohttp) isn't used. `ConnectorGraphQLClient` overrides
  the public `execute_with_token()`, which every generated tool calls, and
  posts with the connector client instead. (The library's own 401 retry
  resends the stale header, and its static bearer can't follow a
  client-credentials token.)
- "Nested tools" are switched off. For every argument-taking field reachable
  from a root, the library registers one more tool: on Medplum that is ~300
  per resource type (`organization_account_list`, ...) and startup never
  finishes. They're turned off with the library's public `apply_mcp(hidden)`.
- The schema is introspected with the full standard query (graphql-core's
  `get_introspection_query`), which `build_client_schema` requires; the
  native engine's trimmed query lacks `interfaces`.

Known limit: the library selects result fields only two levels deep, which
is not configurable (`selection_depth` is ignored here). FHIR data deeper
than that — `type.coding`, `identifier.type`, `contact.*` — is not returned.
"""

import json
import re
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import httpx2
from fastmcp import FastMCP
from fastmcp.server.providers import Provider
from fastmcp.tools import Tool
from graphql import (
    GraphQLObjectType,
    GraphQLSchema,
    build_client_schema,
    get_introspection_query,
    get_named_type,
)
from graphql_mcp import apply_mcp
from graphql_mcp.remote import RemoteGraphQLClient, RemoteGraphQLError
from graphql_mcp.server import add_tools_from_schema_with_remote

from app.core.config import ROOT_DIR, GraphQLPluginConfig
from app.core.logging import get_logger
from app.errors import DiscoveryError
from app.plugins.graphql.introspection import _unwrap
from app.plugins.graphql.provider import prune_nulls

logger = get_logger(__name__)


class ConnectorGraphQLClient(RemoteGraphQLClient):
    """graphql-mcp's remote client, sending through the connector's httpx2
    client (which carries the outbound auth) instead of aiohttp."""

    def __init__(
        self, endpoint: str, client: httpx2.AsyncClient, schema: GraphQLSchema
    ) -> None:
        super().__init__(endpoint, schema=schema)
        self._client = client

    async def execute_with_token(
        self,
        query: str,
        variables: dict[str, Any] | None = None,
        operation_name: str | None = None,
        retry_on_auth_error: bool = True,
        bearer_token_override: str | None = None,
        extra_headers: dict[str, str] | None = None,
    ) -> dict[str, Any]:
        payload: dict[str, Any] = {"query": query}
        if variables:
            payload["variables"] = variables
        if operation_name:
            payload["operationName"] = operation_name
        r = await self._client.post(self.url, json=payload)
        if r.status_code != 200:
            # The library turns any exception into the tool's error message,
            # so put the backend's own body (e.g. an OperationOutcome) in it.
            raise RuntimeError(f"HTTP {r.status_code} from {self.url}: {r.text[:2000]}")
        body = r.json()
        if body.get("errors"):
            raise RemoteGraphQLError(
                body["errors"], body.get("data"), "data" in body, query
            )
        return prune_nulls(body.get("data") or {})


class StaticToolsProvider(Provider):
    """Serves the tools graphql-mcp registered on its scratch server."""

    def __init__(self, tools: Sequence[Tool]) -> None:
        super().__init__()
        self._tools = list(tools)

    async def _list_tools(self) -> Sequence[Tool]:
        return self._tools


async def load_full_schema(
    config: GraphQLPluginConfig, discovery: httpx2.AsyncClient
) -> GraphQLSchema:
    if config.schema_file:
        path = Path(ROOT_DIR / config.schema_file)
        try:
            raw = _unwrap(json.loads(path.read_text(encoding="utf-8")), str(path))
        except (OSError, ValueError) as e:
            raise DiscoveryError(f"cannot read GraphQL schema file {path}: {e}") from e
    else:
        try:
            r = await discovery.post(
                config.endpoint,
                json={"query": get_introspection_query(descriptions=True)},
            )
            r.raise_for_status()
            raw = _unwrap(r.json(), config.endpoint)
        except httpx2.HTTPStatusError as e:
            hint = (
                " — the endpoint needs auth for introspection; set the connector's discovery_token"
                if e.response.status_code in (401, 403)
                else ""
            )
            raise DiscoveryError(
                f"introspection of {config.endpoint} failed: {e}{hint}"
            ) from e
        except (httpx2.HTTPError, ValueError) as e:
            raise DiscoveryError(
                f"introspection of {config.endpoint} failed: {e}"
            ) from e
    try:
        return build_client_schema({"__schema": raw})
    except (TypeError, ValueError) as e:
        raise DiscoveryError(
            f"{config.schema_file or config.endpoint}: not a full introspection result "
            f"(the graphql_mcp engine needs the standard introspection query): {e}"
        ) from e


def _selected(name: str, config: GraphQLPluginConfig) -> bool:
    if any(re.search(p, name) for p in config.exclude):
        return False
    return not config.include or any(re.search(p, name) for p in config.include)


def restrict_tools(schema: GraphQLSchema, config: GraphQLPluginConfig) -> list[str]:
    """Hide (via graphql-mcp's own @mcp(hidden) mechanism) every root field
    the include/exclude rules don't select, and every field of the selected
    roots' result types — the latter only stops nested-tool generation; it
    doesn't affect the selection set. Returns the selected root fields."""
    hidden: dict[str, dict[str, Any]] = {}
    selected: list[str] = []
    roots: list[GraphQLObjectType] = [
        r for r in (schema.query_type, schema.mutation_type) if r
    ]
    for root in roots:
        for name, field in root.fields.items():
            if root is schema.mutation_type and not config.include_mutations:
                continue
            if not _selected(name, config):
                hidden[f"{root.name}.{name}"] = {"hidden": True}
                continue
            selected.append(name)
            result = get_named_type(field.type)
            if isinstance(result, GraphQLObjectType):
                for child in result.fields:
                    hidden[f"{result.name}.{child}"] = {"hidden": True}
    apply_mcp(schema, fields=hidden)
    return selected


async def build_graphql_mcp_provider(
    config: GraphQLPluginConfig,
    *,
    client: httpx2.AsyncClient,
    discovery: httpx2.AsyncClient,
) -> Provider:
    schema = await load_full_schema(config, discovery)
    restrict_tools(schema, config)
    scratch = FastMCP("graphql-mcp")
    add_tools_from_schema_with_remote(
        schema,
        scratch,
        ConnectorGraphQLClient(config.endpoint, client, schema),
        allow_mutations=config.include_mutations,
    )
    tools = list(await scratch.list_tools())
    if not tools:
        logger.warning(
            "No GraphQL fields matched the graphql plugin's include rules",
            extra={"event": "discovery.no_tools", "endpoint": config.endpoint},
        )
    logger.info(
        "Loaded GraphQL tools",
        extra={
            "event": "discovery.loaded",
            "plugin": "graphql",
            "engine": "graphql_mcp",
            "tools": sorted(t.name for t in tools),
        },
    )
    return StaticToolsProvider(tools)
